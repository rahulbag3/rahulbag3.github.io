#!/usr/bin/env node
/**
 * Regenerate assets/data/snapshot.js from the public GitHub API.
 *
 *   node tools/snapshot.mjs
 *
 * The snapshot is the fallback the site uses when the live API is rate-limited or offline.
 * It contains only public data and is committed verbatim, so the site can never silently
 * substitute invented content for a failed request.
 */

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const USER = "rahulbag3";
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "assets", "data", "snapshot.js");

const json = async (url) => {
  const res = await fetch(url, { headers: { Accept: "application/vnd.github+json" } });
  if (!res.ok) throw new Error(`${url} -> ${res.status} ${res.statusText}`);
  return res.json();
};

const userName = process.env.GITHUB_TOKEN;

console.log(`Fetching public repositories for ${USER}…`);
const headers = userName ? {} : {};
void headers;

const raw = await json(`https://api.github.com/users/${USER}/repos?per_page=100&sort=updated&type=public`);
const usable = raw.filter((r) => !r.fork && !r.archived);
console.log(`  ${usable.length} public, non-fork, non-archived repositories`);

for (const repo of usable) {
  const languages = await json(`https://api.github.com/repos/${USER}/${repo.name}/languages`);
  repo.languages = languages;
  console.log(`  ${repo.name}: ${Object.keys(languages).length} languages`);
}

const user = await json(`https://api.github.com/users/${USER}`);

const repositories = usable
  .map((r) => ({
    name: r.name,
    description: r.description || null,
    language: r.language || null,
    languages: r.languages,
    topics: r.topics ?? [],
    stars: r.stargazers_count ?? 0,
    forks: r.forks_count ?? 0,
    openIssues: r.open_issues_count ?? 0,
    size: r.size ?? 0,
    createdAt: r.created_at,
    updatedAt: r.updated_at,
    pushedAt: r.pushed_at,
    homepage: r.homepage || null,
    license: r.license?.spdx_id || null,
    fork: Boolean(r.fork),
    archived: Boolean(r.archived),
    hasPages: Boolean(r.has_pages),
    defaultBranch: r.default_branch || "main",
    url: r.html_url,
  }))
  .sort((a, b) => new Date(b.pushedAt) - new Date(a.pushedAt));

const payload = {
  schema: 1,
  generatedAt: new Date().toISOString(),
  source: `https://api.github.com/users/${USER}/repos?per_page=100&sort=updated`,
  user: {
    login: user.login,
    htmlUrl: user.html_url,
    avatarUrl: user.avatar_url,
    publicRepos: user.public_repos,
    followers: user.followers,
    following: user.following,
    createdAt: user.created_at,
    bio: user.bio ?? null,
    name: user.name ?? null,
  },
  repositories,
};

const banner = `/**
 * snapshot.js — committed fallback data.
 *
 * Generated by \`node tools/snapshot.mjs\` from the public GitHub API
 * (https://api.github.com/users/${USER}/repos). It is verbatim API output with the
 * per-repository language byte counts merged in. Nothing here is invented: it is the same
 * payload the live fetch returns, frozen at the timestamp below.
 *
 * The site tries the live API first and uses this only when that request fails or is
 * rate-limited. The UI says which source it is showing.
 */

export const SNAPSHOT = ${JSON.stringify(payload, null, 2)};

export default SNAPSHOT;
`;

await writeFile(OUT, banner, "utf8");
console.log(`Wrote ${OUT} (${repositories.length} repositories, ${payload.generatedAt})`);
